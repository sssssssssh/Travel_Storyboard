"""M3 — story planner: import AI review requests and generate round-2 proxies.

Round 1 (offline): generated by review_package.py, uploaded by the user.
Round 2: the AI replies with review_requests.json; we import it (with strict
validation) and auto-generate low-res dynamic previews for each requested range.

``direct_analyze`` is the optional in-tool path that talks to a vision model
directly. Audit P1-06 required it to be an honest *director's pass* rather than
"send the first 6 frames and hope":

* frames are chosen by a layered strategy so every selected segment is
  represented, and the prompt binds each image to a concrete
  ``asset_id``/``segment_id``/time range;
* the coverage of the whole library is computed and reported, and anything not
  covered is stated explicitly instead of being silently implied;
* the model's reply is parsed, validated (unknown ids rejected, ranges clamped),
  retried once on malformed output, and the accepted requests are persisted as
  ordinary ``ReviewRequest`` rows so the user can act on them.
"""

