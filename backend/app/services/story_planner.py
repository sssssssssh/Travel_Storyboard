_PRIORITY_ORDER = {"high": 0, "medium": 1, "low": 2}

# --- TSB-243: proxy duration acceptance -------------------------------------
#
# A proxy is only usable if its real duration matches what was asked for. Two
# allowances are needed:
#
#  * absolute — a very short request (0.6 s) is only a few frames, so encoder
#    rounding alone can shift it by a frame or two;
#  * relative — a long request must match proportionally, not just within the
#    absolute window.
#
# Both are generous enough for real encoders and far tighter than the failure
# this guards against (a wrong range or a clamped clip).
PROXY_DURATION_ABS_TOLERANCE_SEC = 0.25
PROXY_DURATION_REL_TOLERANCE = 0.10


def _verify_proxy_duration(requested_sec: float, actual_sec: float) -> None:
    """Raise when a generated proxy's real duration is wrong.

    Checked with ffprobe against the encoded file, so it catches a truncated
    source range, a mis-clamped seek or an encoder that produced almost nothing.
    """
    if not math.isfinite(actual_sec) or actual_sec <= 0:
        raise ReviewValidationError('MEDIA_UNREADABLE', '生成的预览时长无效')

    tolerance = max(
        PROXY_DURATION_ABS_TOLERANCE_SEC,
        requested_sec * PROXY_DURATION_REL_TOLERANCE,
    )
    drift = abs(actual_sec - requested_sec)
    if drift > tolerance:
        raise ReviewValidationError(
            'DURATION_MISMATCH',
            f'预览实际时长 {actual_sec:.3f}s 与请求 {requested_sec:.3f}s 不符'
            f'（偏差 {drift:.3f}s，上限 {tolerance:.3f}s）',
        )

# Budgets for one direct analysis pass.
DEFAULT_MAX_IMAGES = 12
DEFAULT_MAX_SEGMENTS = 60
DEFAULT_MAX_SEGMENTS_SAMPLED = 24


def import_review_requests(project_id: str, data: dict, *, source: str = "ai") -> dict:
    """Partially accept a batch; every rejected/duplicate item remains traceable."""
    created, errors, duplicates = 0, [], []
    with session_scope() as s:
        begin_write(s)
        existing = {(r.asset_id, r.segment_id, round(r.start_sec, 3), round(r.end_sec, 3)): r.id
                    for r in s.scalars(select(ReviewRequest).where(ReviewRequest.project_id == project_id))
                    if r.status not in ('dismissed', 'superseded')}
        for i, item in enumerate(data.get("requests") or []):
            segment_id = item.get('segment_id', '') if isinstance(item, dict) else ''
            try:
                if not isinstance(item, dict):
                    raise ReviewValidationError('INVALID_REQUEST', '请求必须是对象')
                if data.get('project_id') and data['project_id'] != project_id:
                    raise ReviewValidationError('PROJECT_MISMATCH', '导入文件不属于当前项目')
                asset, segment, start, end = validate_review(
                    s, project_id, item.get('asset_id', ''), segment_id,
                    item.get('start_sec'), item.get('end_sec'))
                key = (asset.id, segment.id, start, end)
                if key in existing:
                    duplicates.append({'index': i, 'request_index': i, 'segment_id': segment_id,
                                       'request_id': existing[key], 'message': '相同区间的请求已存在'})
                    continue
                priority = str(item.get('priority') or 'medium').lower()
                row = ReviewRequest(project_id=project_id, asset_id=asset.id, segment_id=segment.id,
                                    start_sec=start, end_sec=end, source=source,
                                    priority=priority if priority in _PRIORITY_ORDER else 'medium',
                                    reason=str(item.get('reason') or '')[:500])
                s.add(row); s.flush()
                existing[key] = row.id
                created += 1
            except ReviewValidationError as exc:
                errors.append({'index': i, 'request_index': i, 'segment_id': str(segment_id),
                               'error_code': exc.code, 'message': str(exc)})
    return {'created': created, 'errors': errors, 'duplicates': duplicates}


@register_task("proxies")
def proxies_task(job_id: str) -> None:
    failures = JobFailures(job_id)
    with session_scope() as s:
        job = s.get(Job, job_id)
        if job is None:
            return
        project_id = job.project_id
        publications = list((job.resume_token or {}).get('proxy_publications', []))
        prior_done = int((job.stats or {}).get('done', 0))
        budget = float((job.config_snapshot or {}).get('max_total_mb', 300)) * 1024 * 1024
        plan = [r.id for r in sorted(s.scalars(select(ReviewRequest).where(
            ReviewRequest.project_id == project_id, ReviewRequest.status == 'pending')).all(),
            key=lambda r: (_PRIORITY_ORDER.get(r.priority, 1), r.created_at, r.id))]
    if not math.isfinite(budget) or budget <= 0:
        raise ValueError('预览预算须为正数')
    root = project_cache_dir(project_id) / 'proxies'
    # Keep these names short. Windows enforces a 260-char path limit by default
    # and a project workspace can already be deep (a custom output_dir plus a
    # 36-char project id); a 69-char staging folder on top of that made ffmpeg
    # write a file the rest of the process could not see (WinError 3).
    staging = root / 'staging' / uuid.uuid4().hex[:12]
    create_owned_staging(project_id, staging, owner_job_id=job_id)
    done, failed, skipped_budget = prior_done, failures.total, 0
    total = prior_done + len(plan)
    total_bytes = sum(p['bytes'] for p in publications)
    files_generated = len(publications)
    requested_duration = sum(p['requested_duration_sec'] for p in publications)
    output_duration = sum(p['output_duration_sec'] for p in publications)
    try:
        for req_id in plan:
            raise_if_cancelled(job_id)
            temp = staging / 'out.mp4'
            final = None
            published = False
            try:
                # Fresh read per item, with no SQLite writer held during encoding.
                with session_scope() as s:
                    rr = s.get(ReviewRequest, req_id)
                    if rr is None or rr.project_id != project_id or rr.status != 'pending':
                        continue
                    asset, segment, start, end = validate_review(
                        s, project_id, rr.asset_id, rr.segment_id, rr.start_sec, rr.end_sec)
                    revision = review_revision(rr, asset, segment)
                    before = verified_source(asset)
                    source_path = asset.source_path
                if total_bytes >= budget:
                    skipped_budget += 1
                    failed += 1
                    failures.record(kind='review_request', ref=req_id,
                                    message='[BUDGET_EXCEEDED] 预览预算已用尽，请增加预算或新建任务；请求仍待处理')
                    failed = failures.total
                    continue
                # TSB-253: pass the job's cancel callback so cancelling stops
                # this encode instead of waiting out the whole clip. Proxies are
                # the longest single encodes in the app, so this is where an
                # un-interruptible ffmpeg hurt most.
                extract_preview(source_path, start, end - start, temp,
                                width=get_settings().proxy_width, keep_audio=True,
                                cancel_check=cancel_check_for(job_id))
                raise_if_cancelled(job_id)
                size = safe_stat(temp).st_size
                media = probe_media(temp)
                if size <= 0 or media.video.width <= 0 or not math.isfinite(media.duration_sec) or media.duration_sec <= 0:
                    # The encoder produced something unreadable — a system
                    # failure, not a problem with the user's request, so this
                    # stays a plain error (→ `failed` / PROXY_FAILED) rather than
                    # being routed to `needs_review`.
                    raise ValueError('生成的预览不可读取')
                # TSB-243: verify the *actual* duration, not just that a file
                # exists. A wrong-length proxy used to be published as `proxied`.
                # A mismatch IS a request/asset problem, so it is raised as a
                # ReviewValidationError and lands in `needs_review`.
                requested = end - start
                _verify_proxy_duration(requested, media.duration_sec)
                if size > budget - total_bytes:
                    skipped_budget += 1
                    failed += 1
                    failures.record(kind='review_request', ref=req_id,
                                    message='[BUDGET_EXCEEDED] 实际预览超过剩余预算，请增加预算；请求仍待处理')
                    failed = failures.total
                    continue
                # Unique final name: rollback can remove only this attempt;
                # historical previews are never overwritten, including DB failure.
                # Short by design (see the staging note above): the request id is
                # tracked in the database, so the filename does not need to repeat it.
                final = root / f'{uuid.uuid4().hex[:16]}.mp4'
                with session_scope() as s:
                    begin_write(s)
                    raise_if_cancelled_in_session(s, job_id)
                    rr = s.get(ReviewRequest, req_id)
                    if rr is None or rr.project_id != project_id or rr.status != 'pending':
                        raise ReviewValidationError('REQUEST_CHANGED', '请求已被暂缓、撤回或替代，旧预览已保留')
                    asset, segment, _, _ = validate_review(
                        s, project_id, rr.asset_id, rr.segment_id, rr.start_sec, rr.end_sec)
                    after = verified_source(asset)
                    if before != after:
                        raise ReviewValidationError('SOURCE_CHANGED', '编码期间源文件发生变化，旧预览已保留')
                    if review_revision(rr, asset, segment) != revision:
                        raise ReviewValidationError('REQUEST_CHANGED', '编码期间镜头或请求发生变化，请重新提交')
                    safe_replace(temp, final)
                    rr.proxy_ref, rr.status = rel_to_data(final), 'proxied'
                    publication = {'request_id': req_id, 'path': rr.proxy_ref, 'bytes': size,
                                   'requested_duration_sec': end - start, 'output_duration_sec': media.duration_sec}
                    current_job = s.get(Job, job_id)
                    current_job.resume_token = {**(current_job.resume_token or {}),
                                                'proxy_publications': publications + [publication]}
                    # Persist counters with the reference: crash recovery cannot
                    # reset a job's budget after a published request disappears
                    # from its pending queue.
                    current_job.stats = {**(current_job.stats or {}), 'total': total,
                        'done': done + 1, 'failed': failed, 'bytes': total_bytes + size,
                        'files_generated': files_generated + 1,
                        'requested_duration_sec': requested_duration + end - start,
                        'output_duration_sec': output_duration + media.duration_sec}
                published = True
                publications.append(publication)
                total_bytes += size
                files_generated += 1
                requested_duration += end - start
                output_duration += media.duration_sec
                failures.resolve(kind='review_request', ref=req_id)
                failed = failures.total
            except JobCancelled:
                raise
            except FFmpegCancelled:
                # TSB-253: a media process stopped by its own cancel callback is
                # a cancellation, not one more failed request. Without this the
                # generic handler below would mark the request `failed`, record
                # a bogus failure and carry on encoding the next clip.
                raise JobCancelled('Proxy generation cancelled by user') from None
            except Exception as exc:  # per-request isolation, including final DB failure
                failed += 1
                code = getattr(exc, 'code', 'PROXY_FAILED')
                failures.record(kind='review_request', ref=req_id, message=f'[{code}] {exc}')
                failed = failures.total
                with session_scope() as s:
                    begin_write(s)
                    rr = s.get(ReviewRequest, req_id)
                    # Never resurrect/overwrite a user disposition.
                    if rr is not None and rr.status == 'pending':
                        rr.status = 'needs_review' if isinstance(exc, ReviewValidationError) else 'failed'
            finally:
                temp.unlink(missing_ok=True)
                if final is not None and not published:
                    final.unlink(missing_ok=True)
                done += 1
                update_job(job_id, stats={'total': total, 'done': done, 'failed': failed,
                    'bytes': total_bytes, 'skipped_budget': skipped_budget, 'files_generated': files_generated,
                    'requested_duration_sec': requested_duration, 'output_duration_sec': output_duration})
    finally:
        # TSB-262: use the restricted helper rather than a bare
        # `rmtree(ignore_errors=True)`, which reports success whether or not the
        # deep-path tree was actually removed and cannot be audited afterwards.
        cleanup_staging_or_log(project_id, staging, owner_job_id=job_id)


def _select_representative_frames(
    project_id: str,
    max_images: int,
    max_segments_sampled: int,
) -> tuple[list[dict], dict]:
    """Pick frames that cover the library, not just the oldest few.

    Layered strategy (audit P1-06):

    1. Take every candidate segment ordered by the user's own signal
       (favorite > like > pending), so deliberate choices are never dropped.
    2. Walk that list round-robin by *asset*, which spreads the sample across
       different source videos instead of exhausting one long clip first.
    3. Within a segment prefer the middle frame — it is the most representative
       of the shot and least likely to be a transition artefact.

    Returns ``(picked, coverage)`` where each picked item carries the binding the
    prompt needs (asset id, segment id, time range, frame time).
    """
    with session_scope() as s:
        segments = s.scalars(
            select(Segment)
            .where(Segment.project_id == project_id, Segment.user_rating != "exclude", Segment.status.not_in(INVALID_SEGMENT_STATUSES))
            .order_by(Segment.created_at)
        ).all()
        total_segments = len(segments)
        candidate_assets = len({seg.asset_id for seg in segments})
        # Everything in the project, for an honest "not covered" number.
        library_assets = len(
            s.scalars(select(Asset).where(Asset.project_id == project_id)).all()
        )

        # A first representative per asset before any second representative.
        # Among first-round assets, their best manual rating wins; ties are stable.
        groups: dict[str, deque] = {}
        for segment in sorted(segments, key=lambda g: (_rating_rank(g.user_rating), g.start_sec, g.id)):
            groups.setdefault(segment.asset_id, deque()).append(segment)
        sampled = []
        while groups and len(sampled) < max_segments_sampled:
            order = sorted(groups, key=lambda aid: (
                _rating_rank(groups[aid][0].user_rating), aid))
            for aid in order:
                if len(sampled) >= max_segments_sampled:
                    break
                sampled.append(groups[aid].popleft())
                if not groups[aid]:
                    del groups[aid]
        seg_ids = [g.id for g in sampled]
        frames_by_seg: dict[str, list[Frame]] = {}
        if seg_ids:
            for f in s.scalars(
                select(Frame).where(Frame.segment_id.in_(seg_ids)).order_by(Frame.time_sec)
            ):
                frames_by_seg.setdefault(f.segment_id, []).append(f)
        asset_names = {
            a.id: a.display_name
            for a in s.scalars(select(Asset).where(Asset.project_id == project_id)).all()
        }
        seg_meta = [
            {
                "segment_id": g.id,
                "asset_id": g.asset_id,
                "alias": asset_names.get(g.asset_id, "unknown"),
                "start_sec": g.start_sec,
                "end_sec": g.end_sec,
                "story_role": g.story_role,
                "user_rating": g.user_rating,
            }
            for g in sampled
        ]

    picked: list[dict] = []
    for meta in seg_meta:
        if len(picked) >= max_images:
            break
        midpoint = (meta["start_sec"] + meta["end_sec"]) / 2
        frames = sorted(frames_by_seg.get(meta["segment_id"], []),
                        key=lambda f: (abs(f.time_sec - midpoint), f.time_sec, f.id))
        for frame in frames:
            if not meta["start_sec"] <= frame.time_sec <= meta["end_sec"]:
                continue
            try:
                path = resolve_in_project(project_id, frame.image_path)
            except ValueError:
                continue
            if not safe_is_file(path):
                continue
            picked.append({**meta, "frame_id": frame.id, "frame_time_sec": frame.time_sec, "path": path})
            break

    covered_segments = len({p["segment_id"] for p in picked})
    covered_assets = len({p["asset_id"] for p in picked})
    candidates_total = len(segments)
    coverage = {
        "library_assets": library_assets,
        "candidate_segments": candidates_total,
        "candidate_assets": candidate_assets,
        "segments_considered": len(sampled),
        "segments_covered_by_images": covered_segments,
        "assets_covered_by_images": covered_assets,
        "images_sent": len(picked),
        "segments_not_covered": max(0, candidates_total - covered_segments),
        "assets_not_covered": max(0, library_assets - covered_assets),
        "candidate_assets_not_covered": max(0, candidate_assets - covered_assets),
        "complete": covered_segments == candidates_total and covered_assets == library_assets and candidates_total > 0,
    }
    return picked, coverage


def _rating_rank(rating: str) -> str:
    return {"favorite": "a", "like": "b", "pending": "c"}.get(rating, "d")


def _extract_json(raw: str) -> dict | None:
    """Pull a JSON object out of a model reply, tolerating code fences."""
    if not raw:
        return None
    text = raw.strip()
    fence = re.search(r"```(?:json)?\s*(.*?)```", text, re.DOTALL)
    if fence:
        text = fence.group(1).strip()
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        start, end = text.find("{"), text.rfind("}")
        if start == -1 or end <= start:
            return None
        try:
            data = json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            return None
    return data if isinstance(data, dict) else None


def _validate_analysis(data: dict, allowed: dict[str, dict]) -> tuple[list[dict], list[str]]:
    """Accept only review requests that point at real, currently-selected shots.

    ``allowed`` maps ``segment_id -> {asset_id, start_sec, end_sec}``. Ids the
    model invented are dropped and reported, never persisted (audit P1-06:
    "甚至生成虚构 ID").
    """
    accepted: list[dict] = []
    problems: list[str] = []

    stories = data.get("stories")
    if stories is not None and not isinstance(stories, list):
        problems.append("stories 不是数组，已忽略")

    requests = data.get("review_requests")
    if requests is None:
        requests = []
    if not isinstance(requests, list):
        return accepted, problems + ["review_requests 不是数组"]

    seen: set[tuple[str, float, float]] = set()
    for i, item in enumerate(requests):
        if not isinstance(item, dict):
            problems.append(f"第 {i} 条不是对象")
            continue
        seg_id = str(item.get("segment_id") or "").strip()
        meta = allowed.get(seg_id)
        if meta is None:
            problems.append(f"第 {i} 条引用了未知 segment_id（已丢弃）")
            continue
        asset_id = str(item.get("asset_id") or meta["asset_id"]).strip()
        if asset_id != meta["asset_id"]:
            problems.append(f"第 {i} 条的 asset_id 与 segment 不匹配（已丢弃）")
            continue
        try:
            start = float(item.get("start_sec", meta["start_sec"]))
            end = float(item.get("end_sec", meta["end_sec"]))
        except (TypeError, ValueError):
            problems.append(f"第 {i} 条时间不是数字（已丢弃）")
            continue
        if not (math.isfinite(start) and math.isfinite(end)) or start < 0 or end <= start:
            problems.append(f"第 {i} 条时间非法或非有限数字（已丢弃）")
            continue
        # Model-only correction is bounded to 50 ms and always reported.
        # The subsequent DB transaction applies the strict current validator.
        if start < meta['start_sec'] - .05 or end > meta['end_sec'] + .05:
            problems.append(f'第 {i} 条超出所见镜头范围（已丢弃）')
            continue
        if start < meta['start_sec'] or end > meta['end_sec']:
            problems.append(f'第 {i} 条模型时间在 0.05 秒内修正至所见镜头边界')
        start = max(meta["start_sec"], min(start, meta["end_sec"]))
        end = max(meta["start_sec"], min(end, meta["end_sec"]))
        try:
            start, end = validate_range(start, end, meta['start_sec'], meta['end_sec'], meta['end_sec'])
        except ReviewValidationError as exc:
            problems.append(f'第 {i} 条 [{exc.code}] {exc}')
            continue
        key = (seg_id, round(start, 2), round(end, 2))
        if key in seen:
            continue
        seen.add(key)
        priority = str(item.get("priority") or "medium").lower()
        if priority not in _PRIORITY_ORDER:
            priority = "medium"
        accepted.append(
            {
                "asset_id": asset_id,
                "segment_id": seg_id,
                "start_sec": round(start, 3),
                "end_sec": round(end, 3),
                "priority": priority,
                "reason": str(item.get("reason") or "")[:500],
            }
        )
    return accepted, problems


def _persist_requests(project_id: str, requests: list[dict]) -> int:
    """Compatibility helper; direct and imported requests share strict admission."""
    return import_review_requests(project_id, {'requests': requests}, source='direct')['created']


def direct_analyze(
    project_id: str,
    max_images: int = DEFAULT_MAX_IMAGES,
    max_segments_sampled: int = DEFAULT_MAX_SEGMENTS_SAMPLED,
    *,
    authorization=None,
) -> dict:
    """Optional in-tool round-1 analysis via a configured vision model.

    Returns a report plus the review requests that survived validation, and a
    ``coverage`` block describing exactly how much of the library the model
    actually saw (audit P1-06).

    TSB-312: ``authorization`` is the per-call consent token. The HTTP route
    obtains it from the shared authorization boundary before calling here, so
    this function cannot upload on its own — the provider refuses an unguarded
    request as well.
    """
    if not model_client.is_configured():
        return {
            "configured": False,
            "report": "",
            "stories": [],
            "review_requests": [],
            "coverage": {},
            "message": "Model not configured; use the offline package instead.",
        }

    picked, coverage = _select_representative_frames(
        project_id, max_images, max_segments_sampled
    )
    if not picked:
        return {
            "configured": True,
            "report": "",
            "stories": [],
            "review_requests": [],
            "coverage": coverage,
            "message": "没有可用的代表帧，请先完成片段检测。",
        }

    # Bind every image to its identifiers so the model cannot confuse shots.
    manifest_lines = [
        f"image {i + 1}: asset_id={p['asset_id']} segment_id={p['segment_id']} "
        f"shot={p['start_sec']:.1f}-{p['end_sec']:.1f}s frame_at={p['frame_time_sec']:.1f}s "
        f"source={p['alias']} role={p['story_role'] or 'unspecified'} rating={p['user_rating']}"
        for i, p in enumerate(picked)
    ]
    allowed = {
        p["segment_id"]: {
            "asset_id": p["asset_id"],
            "start_sec": p["start_sec"],
            "end_sec": p["end_sec"],
        }
        for p in picked
    }

    prompt = "\n".join(
        [
            "You are a travel-film director. You are shown representative frames from",
            "candidate shots of ONE trip. Each image is identified below.",
            "",
            "IMAGE INDEX (use these exact identifiers, never invent new ones):",
            *manifest_lines,
            "",
            f"COVERAGE: you are seeing {coverage['segments_covered_by_images']} of "
            f"{coverage['candidate_segments']} candidate shots across "
            f"{coverage['assets_covered_by_images']} of {coverage['library_assets']} source videos.",
            "If that is a small fraction, say so explicitly in your report — do not",
            "generalise about footage you were not shown.",
            "",
            "Tasks:",
            "1. Propose 2-3 distinct story lines that could be cut from these shots.",
            "2. For any shot whose motion or audio you need to verify before trusting it,",
            "   emit a review request pointing at a real segment_id above.",
            "",
            "Respond with ONLY this JSON object (no markdown fences):",
            '{"report": "your reasoning, including what you could NOT judge",',
            ' "stories": [{"title": "...", "logline": "...", "segment_ids": ["..."]}],',
            ' "review_requests": [{"asset_id": "...", "segment_id": "...",',
            '   "start_sec": 12.0, "end_sec": 18.0, "priority": "high",',
            '   "reason": "need to check camera shake"}]}',
        ]
    )

    messages = [
        {"role": "system", "content": "You return strict JSON only, no markdown fences."},
        model_client.image_message(prompt, [p["path"] for p in picked]),
    ]

    raw = model_client.chat(messages, authorization=authorization)
    data = _extract_json(raw)
    problems: list[str] = []
    retried = False

    if data is None:
        # One retry: models occasionally wrap JSON in prose.
        retried = True
        retry_messages = messages + [
            {"role": "assistant", "content": raw[:2000]},
            {
                "role": "user",
                "content": "That was not valid JSON. Reply with ONLY the JSON object.",
            },
        ]
        raw = model_client.chat(retry_messages, authorization=authorization)
        data = _extract_json(raw)

    if data is None:
        return {
            "configured": True,
            "report": "",
            "stories": [],
            "review_requests": [],
            "coverage": coverage,
            "raw": raw,
            "problems": ["模型返回的不是合法 JSON（已重试一次）"],
            "created": 0,
        }

    accepted, problems = _validate_analysis(data, allowed)
    persistence = import_review_requests(project_id, {'requests': accepted}, source='direct')
    created = persistence['created']
    problems.extend(f"第 {e['index']} 条 [{e['error_code']}] {e['message']}" for e in persistence['errors'])
    if persistence['duplicates']:
        problems.append('部分请求已存在，未重复新增。')

    stories = data.get("stories")
    if not isinstance(stories, list):
        stories = []
    # Drop story references to shots the model never saw.
    cleaned_stories = []
    for st in stories:
        if not isinstance(st, dict):
            continue
        ids = [i for i in (st.get("segment_ids") or []) if i in allowed]
        cleaned_stories.append(
            {
                "title": str(st.get("title") or "")[:200],
                "logline": str(st.get("logline") or "")[:500],
                "segment_ids": ids,
                "unknown_segment_ids": [
                    i for i in (st.get("segment_ids") or []) if i not in allowed
                ],
            }
        )

    return {
        "configured": True,
        "report": str(data.get("report") or ""),
        "stories": cleaned_stories,
        "review_requests": accepted,
        "coverage": coverage,
        "problems": problems,
        "retried": retried,
        "created": created,
        "raw": raw,
    }
