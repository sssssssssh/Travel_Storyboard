"""M3 — story planner: import AI review requests and generate round-2 proxies.

Round 1 (offline): generated by review_package.py, uploaded by the user.
Round 2: the AI replies with review_requests.json; we import it (with strict
validation) and auto-generate low-res dynamic previews for each requested range.
"""

from __future__ import annotations

import logging
from pathlib import Path

from sqlalchemy import select

from ..config import get_settings
from ..database import session_scope
from ..ffmpeg import extract_preview
from ..models import Asset, Frame, Job, ReviewRequest, Segment
from ..paths import project_cache_dir, rel_to_data
from . import model_client
from .runner import JobFailures, raise_if_cancelled, register_task, update_job

logger = logging.getLogger(__name__)

_PRIORITY_ORDER = {"high": 0, "medium": 1, "low": 2}


def import_review_requests(project_id: str, data: dict) -> dict:
    """Validate and persist review_requests.json (doc §1.5 / §3.3)."""
    requests = data.get("requests") or []
    created = 0
    errors: list[dict] = []

    with session_scope() as s:
        assets = {
            a.id: a for a in s.scalars(select(Asset).where(Asset.project_id == project_id)).all()
        }
        segments = {
            g.id: g for g in s.scalars(select(Segment).where(Segment.project_id == project_id)).all()
        }
        for i, item in enumerate(requests):
            if not isinstance(item, dict):
                errors.append({"index": i, "message": "request must be an object"})
                continue

            problems: list[str] = []
            asset = assets.get(item.get("asset_id", ""))
            seg = segments.get(item.get("segment_id", ""))
            if not asset:
                problems.append("asset_id not found")
            if not seg:
                problems.append("segment_id not found")

            start = item.get("start_sec")
            end = item.get("end_sec")
            try:
                start = float(start)
                end = float(end)
            except (TypeError, ValueError):
                start = end = None
                problems.append("start_sec/end_sec must be numbers")

            if start is not None and end is not None and start >= end:
                problems.append("start_sec must be < end_sec")
            if asset and start is not None and end is not None:
                if start < 0 or end > asset.duration_sec + 1e-3:
                    problems.append("time range exceeds source duration")
            if asset and seg and seg.asset_id != asset.id:
                problems.append("segment does not belong to asset")

            if problems:
                errors.append({"index": i, "message": "; ".join(problems)})
                continue

            s.add(
                ReviewRequest(
                    project_id=project_id,
                    asset_id=item["asset_id"],
                    segment_id=item["segment_id"],
                    start_sec=start,
                    end_sec=end,
                    priority=item.get("priority", "medium"),
                    reason=item.get("reason", ""),
                )
            )
            created += 1

    return {"created": created, "errors": errors}


@register_task("proxies")
def proxies_task(job_id: str) -> None:
    failures = JobFailures(job_id)
    with session_scope() as s:
        job = s.get(Job, job_id)
        if job is None:
            return
        project_id = job.project_id
        max_total_mb = float((job.config_snapshot or {}).get("max_total_mb", 300))
        s.expunge(job)

    settings = get_settings()
    (project_cache_dir(project_id) / "proxies").mkdir(parents=True, exist_ok=True)
    with session_scope() as s:
        reqs = s.scalars(
            select(ReviewRequest).where(
                ReviewRequest.project_id == project_id, ReviewRequest.status == "pending"
            )
        ).all()
        assets = {
            a.id: a for a in s.scalars(select(Asset).where(Asset.project_id == project_id)).all()
        }
        reqs = sorted(reqs, key=lambda r: _PRIORITY_ORDER.get(r.priority, 1))
        plan = [(r.id, r.asset_id, r.start_sec, r.end_sec, r.priority) for r in reqs]

    total = len(plan)
    done = 0
    failed = 0
    skipped_budget = 0
    total_bytes = 0
    budget = max_total_mb * 1024 * 1024

    for req_id, asset_id, start_sec, end_sec, _priority in plan:
        raise_if_cancelled(job_id)
        asset = assets.get(asset_id)
        if asset is None:
            failed += 1
            failures.record(
                kind="review_request", ref=req_id, message=f"asset {asset_id} not found"
            )
            done += 1
            update_job(
                job_id,
                stats={"total": total, "done": done, "failed": failed, "bytes": total_bytes},
            )
            continue
        if total_bytes >= budget:
            # Budget exhausted: leave the request pending rather than silently
            # dropping it (audit P2-3).
            skipped_budget += 1
            continue
        dur = max(1.0, end_sec - start_sec)
        out = project_cache_dir(project_id) / "proxies" / f"{req_id}.mp4"
        try:
            extract_preview(
                asset.source_path,
                start_sec,
                dur,
                out,
                width=settings.proxy_width,
                keep_audio=True,
            )
            size = out.stat().st_size
            total_bytes += size
            with session_scope() as s:
                rr = s.get(ReviewRequest, req_id)
                rr.proxy_ref = rel_to_data(out)
                rr.status = "proxied"
        except Exception as exc:  # noqa: BLE001 - per-request isolation
            logger.exception("Proxy failed for request %s", req_id)
            failed += 1
            failures.record(
                kind="review_request",
                ref=req_id,
                message=f"{asset.display_name} {start_sec:.1f}-{end_sec:.1f}s: {exc}",
            )
            with session_scope() as s:
                rr = s.get(ReviewRequest, req_id)
                rr.status = "failed"
                rr.reason = (rr.reason or "") + f" [proxy failed: {str(exc)[:200]}]"
        done += 1
        update_job(
            job_id,
            stats={
                "total": total,
                "done": done,
                "failed": failed,
                "bytes": total_bytes,
                "skipped_budget": skipped_budget,
            },
        )


def direct_analyze(project_id: str, max_images: int = 6) -> dict:
    """Optional in-tool round-1 analysis via a configured vision model."""
    if not model_client.is_configured():
        return {
            "configured": False,
            "report": "",
            "review_requests": [],
            "message": "Model not configured; use the offline package instead.",
        }

    with session_scope() as s:
        segments = s.scalars(
            select(Segment)
            .where(Segment.project_id == project_id, Segment.user_rating != "exclude")
            .order_by(Segment.created_at)
            .limit(40)
        ).all()
        frames = []
        if segments:
            frames = s.scalars(
                select(Frame)
                .where(Frame.segment_id.in_([g.id for g in segments]))
                .order_by(Frame.time_sec)
                .limit(max_images)
            ).all()

    from ..paths import resolve_from_data

    image_paths = [resolve_from_data(f.image_path) for f in frames if f.image_path]
    prompt = (
        "You are a travel-film director. Given representative frames from candidate shots, "
        "propose at least two story lines and, for shots needing motion/audio verification, "
        "return review requests. Respond ONLY with JSON: "
        '{"report": "...", "review_requests": [{"asset_id":"...","segment_id":"...",'
        '"start_sec":0.0,"end_sec":0.0,"priority":"high","reason":"..."}]}'
    )
    messages = [
        {"role": "system", "content": "You return strict JSON only, no markdown fences."},
        model_client.image_message(prompt, image_paths),
    ]
    raw = model_client.chat(messages)
    return {"configured": True, "raw": raw}
